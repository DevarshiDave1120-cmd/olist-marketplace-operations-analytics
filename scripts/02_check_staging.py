"""Step 3 check: staging row counts vs raw, plus flag counts. Writes docs/staging_counts.md.

Run from the repo root:  conda run -n olist python scripts/02_check_staging.py
"""
from datetime import datetime
from pathlib import Path

import snowflake.connector

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "staging_counts.md"

# staging model -> SQL for the expected raw count
PAIRS = {
    "STG_CUSTOMERS": "SELECT COUNT(*) FROM RAW.CUSTOMERS",
    "STG_GEOLOCATION": "SELECT COUNT(DISTINCT geolocation_zip_code_prefix) FROM RAW.GEOLOCATION",
    "STG_ORDER_ITEMS": "SELECT COUNT(*) FROM RAW.ORDER_ITEMS",
    "STG_ORDER_PAYMENTS": "SELECT COUNT(*) FROM RAW.ORDER_PAYMENTS",
    "STG_ORDER_REVIEWS": "SELECT COUNT(*) FROM RAW.ORDER_REVIEWS",
    "STG_ORDERS": "SELECT COUNT(*) FROM RAW.ORDERS",
    "STG_PRODUCTS": "SELECT COUNT(*) FROM RAW.PRODUCTS",
    "STG_SELLERS": "SELECT COUNT(*) FROM RAW.SELLERS",
    "STG_PRODUCT_CATEGORY_TRANSLATION": "SELECT COUNT(*) FROM RAW.PRODUCT_CATEGORY_NAME_TRANSLATION",
}

FLAG_QUERIES = [
    ("stg_orders: total", "SELECT COUNT(*) FROM STAGING.STG_ORDERS"),
    ("stg_orders: is_in_analysis_window", "SELECT COUNT_IF(is_in_analysis_window) FROM STAGING.STG_ORDERS"),
    ("stg_orders: is_delivered_with_date", "SELECT COUNT_IF(is_delivered_with_date) FROM STAGING.STG_ORDERS"),
    ("stg_orders: has_impossible_timestamps", "SELECT COUNT_IF(has_impossible_timestamps) FROM STAGING.STG_ORDERS"),
    ("stg_orders: in window AND delivered with date",
     "SELECT COUNT_IF(is_in_analysis_window AND is_delivered_with_date) FROM STAGING.STG_ORDERS"),
    ("stg_orders: ...of which have impossible timestamps (excluded from delivery metrics)",
     "SELECT COUNT_IF(is_in_analysis_window AND is_delivered_with_date AND has_impossible_timestamps) "
     "FROM STAGING.STG_ORDERS"),
    ("stg_orders: delivery-metric base (window, delivered, no impossible timestamps)",
     "SELECT COUNT_IF(is_in_analysis_window AND is_delivered_with_date AND NOT has_impossible_timestamps) "
     "FROM STAGING.STG_ORDERS"),
    ("stg_order_reviews: is_latest_review_for_order",
     "SELECT COUNT_IF(is_latest_review_for_order) FROM STAGING.STG_ORDER_REVIEWS"),
    ("stg_order_reviews: distinct order_id", "SELECT COUNT(DISTINCT order_id) FROM STAGING.STG_ORDER_REVIEWS"),
    ("stg_order_reviews: orders with != 1 latest review (should be 0)",
     "SELECT COUNT(*) FROM (SELECT order_id FROM STAGING.STG_ORDER_REVIEWS GROUP BY 1 "
     "HAVING COUNT_IF(is_latest_review_for_order) <> 1)"),
    ("stg_products: has_category = false", "SELECT COUNT_IF(NOT has_category) FROM STAGING.STG_PRODUCTS"),
    ("stg_products: has category but not translated",
     "SELECT COUNT_IF(has_category AND NOT is_category_translated) FROM STAGING.STG_PRODUCTS"),
    ("stg_geolocation: raw points (sum)", "SELECT SUM(raw_point_count) FROM STAGING.STG_GEOLOCATION"),
    ("stg_geolocation: points dropped (outside Brazil)",
     "SELECT SUM(raw_point_count - valid_point_count) FROM STAGING.STG_GEOLOCATION"),
    ("stg_geolocation: zips with no valid point",
     "SELECT COUNT_IF(NOT has_valid_point) FROM STAGING.STG_GEOLOCATION"),
]


def main():
    conn = snowflake.connector.connect(connection_name="olist")
    cur = conn.cursor()
    cur.execute("USE WAREHOUSE OLIST_WH")
    cur.execute("USE DATABASE OLIST")
    one = lambda sql: cur.execute(sql).fetchone()[0]

    md = ["# Staging row counts vs raw", "",
          f"Generated by `scripts/02_check_staging.py` on {datetime.now():%Y-%m-%d %H:%M}.", "",
          "## Row counts", "",
          "| staging model | raw expected | staging rows | match |", "|---|---:|---:|---|"]
    all_ok = True
    for model, raw_sql in PAIRS.items():
        exp, got = one(raw_sql), one(f"SELECT COUNT(*) FROM STAGING.{model}")
        all_ok &= exp == got
        md.append(f"| {model.lower()} | {exp:,} | {got:,} | {'OK' if exp == got else 'MISMATCH'} |")
    md += ["", "stg_geolocation is compared with distinct zip prefixes in RAW.GEOLOCATION "
           "(grain is one row per zip).", "", "## Flag counts", "", "| check | count |", "|---|---:|"]
    for label, sql in FLAG_QUERIES:
        md.append(f"| {label} | {one(sql):,} |")

    try:
        cur.execute("ALTER WAREHOUSE OLIST_WH SUSPEND")
    except snowflake.connector.errors.ProgrammingError:
        pass
    conn.close()
    OUT.write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0 if all_ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
