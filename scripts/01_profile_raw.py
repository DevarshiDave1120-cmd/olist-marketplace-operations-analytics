"""Step 2: profile the 9 raw Olist tables in Snowflake OLIST.RAW.

Data-quality profile only -- no business metrics (late rates, review scores,
retention, etc.). Writes docs/raw_profile.md.

Run from the repo root:  conda run -n olist python scripts/01_profile_raw.py
"""
from datetime import datetime
from decimal import Decimal
from pathlib import Path

import snowflake.connector

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "raw_profile.md"

TABLES = [
    "CUSTOMERS", "GEOLOCATION", "ORDER_ITEMS", "ORDER_PAYMENTS", "ORDER_REVIEWS",
    "ORDERS", "PRODUCTS", "SELLERS", "PRODUCT_CATEGORY_NAME_TRANSLATION",
]

# Candidate primary keys (GEOLOCATION has none by design -- profiled separately).
PRIMARY_KEYS = {
    "CUSTOMERS": ["customer_id"],
    "ORDER_ITEMS": ["order_id", "order_item_id"],
    "ORDER_PAYMENTS": ["order_id", "payment_sequential"],
    "ORDER_REVIEWS": ["review_id"],
    "ORDERS": ["order_id"],
    "PRODUCTS": ["product_id"],
    "SELLERS": ["seller_id"],
    "PRODUCT_CATEGORY_NAME_TRANSLATION": ["product_category_name"],
}

# (left table, left col, right table, right col) -- orphans checked both directions.
JOINS = [
    ("ORDERS", "customer_id", "CUSTOMERS", "customer_id"),
    ("ORDER_ITEMS", "order_id", "ORDERS", "order_id"),
    ("ORDER_PAYMENTS", "order_id", "ORDERS", "order_id"),
    ("ORDER_REVIEWS", "order_id", "ORDERS", "order_id"),
    ("ORDER_ITEMS", "product_id", "PRODUCTS", "product_id"),
    ("ORDER_ITEMS", "seller_id", "SELLERS", "seller_id"),
    ("PRODUCTS", "product_category_name", "PRODUCT_CATEGORY_NAME_TRANSLATION", "product_category_name"),
    ("CUSTOMERS", "customer_zip_code_prefix", "GEOLOCATION", "geolocation_zip_code_prefix"),
    ("SELLERS", "seller_zip_code_prefix", "GEOLOCATION", "geolocation_zip_code_prefix"),
]


class Profiler:
    def __init__(self, cur):
        self.cur = cur
        self.md: list[str] = []

    def q(self, sql):
        self.cur.execute(sql)
        cols = [d[0].lower() for d in self.cur.description]
        return cols, self.cur.fetchall()

    def scalar(self, sql):
        return self.q(sql)[1][0][0]

    def h(self, text, level=2):
        self.md += [f"{'#' * level} {text}", ""]

    def p(self, text):
        self.md += [text, ""]

    def table(self, cols, rows):
        def fmt(v):
            if v is None:
                return ""
            if isinstance(v, Decimal):
                v = int(v) if v == v.to_integral_value() else float(v)
            if isinstance(v, int):
                return f"{v:,}"
            if isinstance(v, float):
                return f"{v:,.2f}"
            return str(v)
        self.md.append("| " + " | ".join(cols) + " |")
        self.md.append("|" + "|".join("---" for _ in cols) + "|")
        for r in rows:
            self.md.append("| " + " | ".join(fmt(v) for v in r) + " |")
        self.md.append("")

    def sql_table(self, sql):
        self.table(*self.q(sql))


def columns_of(prof, table):
    _, rows = prof.q(
        "SELECT column_name, data_type FROM OLIST.INFORMATION_SCHEMA.COLUMNS "
        f"WHERE table_schema = 'RAW' AND table_name = '{table}' ORDER BY ordinal_position"
    )
    return rows


def main():
    conn = snowflake.connector.connect(connection_name="olist")
    cur = conn.cursor()
    cur.execute("USE WAREHOUSE OLIST_WH")
    cur.execute("USE SCHEMA OLIST.RAW")
    P = Profiler(cur)

    P.h("Raw data profile — OLIST.RAW", 1)
    P.p(f"Generated by `scripts/01_profile_raw.py` on {datetime.now():%Y-%m-%d %H:%M}. "
        "Data-quality profile only; no business metrics.")

    # 1. Row counts --------------------------------------------------------
    P.h("1. Row counts")
    P.table(["table", "rows"], [(t, P.scalar(f"SELECT COUNT(*) FROM {t}")) for t in TABLES])

    # 2. Primary-key uniqueness ---------------------------------------------
    P.h("2. Primary-key uniqueness")
    rows = []
    for t, keys in PRIMARY_KEYS.items():
        k = ", ".join(keys)
        total, distinct, null_keys = P.q(
            f"SELECT COUNT(*), (SELECT COUNT(*) FROM (SELECT DISTINCT {k} FROM {t})), "
            f"COUNT_IF({' OR '.join(c + ' IS NULL' for c in keys)}) FROM {t}"
        )[1][0]
        rows.append((t, k, total, distinct, total - distinct, null_keys,
                     "unique" if total == distinct and null_keys == 0 else "NOT unique"))
    P.table(["table", "key", "rows", "distinct keys", "duplicate rows", "null keys", "result"], rows)

    # 3. Nulls per column ---------------------------------------------------
    P.h("3. Nulls per column")
    P.p("Only columns with at least one null are listed.")
    rows = []
    for t in TABLES:
        cols = columns_of(P, t)
        exprs = ", ".join(f"COUNT_IF({c} IS NULL)" for c, _ in cols)
        total, *nulls = P.q(f"SELECT COUNT(*), {exprs} FROM {t}")[1][0]
        for (c, _), n in zip(cols, nulls):
            if n:
                rows.append((t, c.lower(), n, f"{100 * n / total:.2f}%"))
    P.table(["table", "column", "nulls", "% of rows"], rows)

    # 4. Date ranges --------------------------------------------------------
    P.h("4. Date ranges")
    rows = []
    for t in TABLES:
        for c, dtype in columns_of(P, t):
            if dtype.startswith("TIMESTAMP"):
                mn, mx = P.q(f"SELECT MIN({c}), MAX({c}) FROM {t}")[1][0]
                rows.append((t, c.lower(), mn, mx))
    P.table(["table", "column", "min", "max"], rows)

    # 5. Join coverage / orphans -------------------------------------------
    P.h("5. How the tables join (orphan keys)")
    P.p("Distinct key values present on one side but missing on the other. "
        "Null keys are excluded.")
    rows = []
    for lt, lc, rt, rc in JOINS:
        l_orph = P.scalar(
            f"SELECT COUNT(DISTINCT l.{lc}) FROM {lt} l LEFT JOIN (SELECT DISTINCT {rc} FROM {rt}) r "
            f"ON l.{lc} = r.{rc} WHERE l.{lc} IS NOT NULL AND r.{rc} IS NULL")
        r_orph = P.scalar(
            f"SELECT COUNT(DISTINCT r.{rc}) FROM {rt} r LEFT JOIN (SELECT DISTINCT {lc} FROM {lt}) l "
            f"ON r.{rc} = l.{lc} WHERE r.{rc} IS NOT NULL AND l.{lc} IS NULL")
        l_rows = P.scalar(
            f"SELECT COUNT(*) FROM {lt} WHERE {lc} IS NOT NULL AND {lc} NOT IN "
            f"(SELECT {rc} FROM {rt} WHERE {rc} IS NOT NULL)")
        rows.append((f"{lt}.{lc.lower()} → {rt}.{rc.lower()}", l_orph, l_rows, r_orph))
    P.table(["join", f"left keys missing on right", "left rows affected",
             "right keys never referenced by left"], rows)

    # 6. Focus areas --------------------------------------------------------
    P.h("6. Focus areas")

    P.h("6a. customer_id vs customer_unique_id", 3)
    P.sql_table("""
        SELECT COUNT(*) AS total_rows, COUNT(DISTINCT customer_id) AS distinct_customer_id,
               COUNT(DISTINCT customer_unique_id) AS distinct_customer_unique_id
        FROM CUSTOMERS""")
    P.p("How many customer_id values map to each customer_unique_id:")
    P.sql_table("""
        SELECT n_customer_ids AS customer_ids_per_unique_id, COUNT(*) AS unique_ids
        FROM (SELECT customer_unique_id, COUNT(DISTINCT customer_id) AS n_customer_ids
              FROM CUSTOMERS GROUP BY 1)
        GROUP BY 1 ORDER BY 1""")
    P.p("Orders per customer_id (checks whether customer_id is one-per-order):")
    P.sql_table("""
        SELECT n_orders AS orders_per_customer_id, COUNT(*) AS customer_ids
        FROM (SELECT customer_id, COUNT(*) AS n_orders FROM ORDERS GROUP BY 1)
        GROUP BY 1 ORDER BY 1""")

    P.h("6b. Order statuses", 3)
    P.sql_table("""
        SELECT order_status, COUNT(*) AS orders,
               ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 2) AS pct
        FROM ORDERS GROUP BY 1 ORDER BY 2 DESC""")

    P.h("6c. Orders missing timestamps, by status", 3)
    P.sql_table("""
        SELECT order_status, COUNT(*) AS orders,
               COUNT_IF(order_approved_at IS NULL) AS no_approved,
               COUNT_IF(order_delivered_carrier_date IS NULL) AS no_carrier_date,
               COUNT_IF(order_delivered_customer_date IS NULL) AS no_customer_delivery,
               COUNT_IF(order_estimated_delivery_date IS NULL) AS no_estimate
        FROM ORDERS GROUP BY 1 ORDER BY 2 DESC""")
    P.p("Timestamp sequence anomalies (all orders, nulls skipped):")
    P.sql_table("""
        SELECT
          COUNT_IF(order_status = 'delivered' AND order_delivered_customer_date IS NULL)
              AS delivered_status_without_delivery_date,
          COUNT_IF(order_status <> 'delivered' AND order_delivered_customer_date IS NOT NULL)
              AS not_delivered_status_with_delivery_date,
          COUNT_IF(order_approved_at < order_purchase_timestamp) AS approved_before_purchase,
          COUNT_IF(order_delivered_carrier_date < order_purchase_timestamp) AS carrier_before_purchase,
          COUNT_IF(order_delivered_customer_date < order_delivered_carrier_date)
              AS customer_delivery_before_carrier
        FROM ORDERS""")

    P.h("6d. Duplicate review IDs", 3)
    P.sql_table("""
        WITH d AS (SELECT review_id, COUNT(*) AS n, COUNT(DISTINCT order_id) AS n_orders
                   FROM ORDER_REVIEWS GROUP BY 1 HAVING COUNT(*) > 1)
        SELECT COUNT(*) AS duplicated_review_ids, COALESCE(SUM(n), 0) AS rows_involved,
               COUNT_IF(n_orders > 1) AS review_ids_spanning_multiple_orders,
               (SELECT COUNT(*) FROM (SELECT DISTINCT review_id, order_id FROM ORDER_REVIEWS))
                   AS distinct_review_order_pairs
        FROM d""")
    P.p("Reviews per order:")
    P.sql_table("""
        SELECT n AS reviews_per_order, COUNT(*) AS orders
        FROM (SELECT order_id, COUNT(*) AS n FROM ORDER_REVIEWS GROUP BY 1)
        GROUP BY 1 ORDER BY 1""")
    P.p("Orders with no review row:")
    P.sql_table("""
        SELECT COUNT(*) AS orders_without_review FROM ORDERS o
        WHERE NOT EXISTS (SELECT 1 FROM ORDER_REVIEWS r WHERE r.order_id = o.order_id)""")

    P.h("6e. Geolocation duplicates per zip prefix", 3)
    P.sql_table("""
        WITH z AS (SELECT geolocation_zip_code_prefix AS zip, COUNT(*) AS n,
                          COUNT(DISTINCT geolocation_lat, geolocation_lng) AS n_points,
                          COUNT(DISTINCT geolocation_state) AS n_states
                   FROM GEOLOCATION GROUP BY 1)
        SELECT COUNT(*) AS distinct_zip_prefixes, SUM(n) AS total_rows,
               ROUND(AVG(n), 1) AS avg_rows_per_zip, MEDIAN(n) AS median_rows_per_zip,
               MAX(n) AS max_rows_per_zip, COUNT_IF(n = 1) AS zips_with_one_row,
               COUNT_IF(n_points > 1) AS zips_with_multiple_coordinates,
               COUNT_IF(n_states > 1) AS zips_spanning_multiple_states
        FROM z""")
    P.sql_table("""
        SELECT (SELECT COUNT(*) FROM GEOLOCATION)
                 - (SELECT COUNT(*) FROM (SELECT DISTINCT * FROM GEOLOCATION))
                 AS exact_duplicate_rows,
               COUNT_IF(geolocation_lat NOT BETWEEN -34 AND 5.5
                        OR geolocation_lng NOT BETWEEN -74 AND -34)
                 AS rows_outside_brazil_bounding_box
        FROM GEOLOCATION""")

    P.h("6f. Orders per purchase month (edge months)", 3)
    _, months = P.q("""
        SELECT TO_CHAR(DATE_TRUNC('month', order_purchase_timestamp), 'YYYY-MM') AS month,
               COUNT(*) AS orders
        FROM ORDERS GROUP BY 1 ORDER BY 1""")
    # Fill calendar gaps so months with zero orders are visible.
    found = dict(months)
    y, m = map(int, months[0][0].split("-"))
    months = []
    while f"{y:04d}-{m:02d}" <= max(found):
        key = f"{y:04d}-{m:02d}"
        months.append((key, found.get(key, 0)))
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    counts = sorted(n for _, n in months)
    median = counts[len(counts) // 2]
    P.p(f"Months flagged `thin` have fewer than 10% of the median month's orders "
        f"(median = {median:,}). This only flags sparse months; the analysis window "
        "is decided later.")
    P.table(["month", "orders", "flag"],
            [(m, n, "thin" if n < 0.1 * median else "") for m, n in months])

    P.h("6g. Payment totals vs item price + freight (per order)", 3)
    P.p("Per order: payment total = SUM(payment_value); item total = SUM(price + freight_value). "
        "Match = absolute difference ≤ 0.01. Reasons for mismatches are investigated in Step 5.")
    recon = """
        WITH i AS (SELECT order_id, SUM(price + freight_value) AS item_total FROM ORDER_ITEMS GROUP BY 1),
             p AS (SELECT order_id, SUM(payment_value) AS pay_total FROM ORDER_PAYMENTS GROUP BY 1),
             j AS (SELECT o.order_id, i.item_total, p.pay_total, p.pay_total - i.item_total AS diff
                   FROM ORDERS o LEFT JOIN i USING (order_id) LEFT JOIN p USING (order_id))
    """
    P.sql_table(recon + """
        SELECT CASE
                 WHEN item_total IS NULL AND pay_total IS NULL THEN 'no items, no payments'
                 WHEN item_total IS NULL THEN 'payments but no items'
                 WHEN pay_total IS NULL THEN 'items but no payments'
                 WHEN ABS(diff) <= 0.01 THEN 'match (abs diff <= 0.01)'
                 WHEN diff > 0 THEN 'payment > items + freight'
                 ELSE 'payment < items + freight'
               END AS category,
               COUNT(*) AS orders,
               ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 2) AS pct
        FROM j GROUP BY 1 ORDER BY 2 DESC""")
    P.p("Size of the mismatches (orders with both items and payments, |diff| > 0.01):")
    P.sql_table(recon + """
        SELECT CASE WHEN ABS(diff) <= 1 THEN '0.01–1.00'
                    WHEN ABS(diff) <= 10 THEN '1.01–10.00'
                    WHEN ABS(diff) <= 100 THEN '10.01–100.00'
                    ELSE '> 100.00' END AS abs_diff_bucket,
               COUNT(*) AS orders
        FROM j WHERE item_total IS NOT NULL AND pay_total IS NOT NULL AND ABS(diff) > 0.01
        GROUP BY 1 ORDER BY MIN(ABS(diff))""")
    P.p("Payment rows by payment_type (context for Step 5):")
    P.sql_table("""
        SELECT payment_type, COUNT(*) AS payment_rows,
               COUNT_IF(payment_value = 0) AS zero_value_rows,
               COUNT_IF(payment_installments = 0) AS zero_installment_rows
        FROM ORDER_PAYMENTS GROUP BY 1 ORDER BY 2 DESC""")
    P.p("Products whose category has no English translation:")
    P.sql_table("""
        SELECT p.product_category_name, COUNT(*) AS products
        FROM PRODUCTS p LEFT JOIN PRODUCT_CATEGORY_NAME_TRANSLATION t USING (product_category_name)
        WHERE p.product_category_name IS NOT NULL AND t.product_category_name IS NULL
        GROUP BY 1 ORDER BY 2 DESC""")

    try:
        cur.execute("ALTER WAREHOUSE OLIST_WH SUSPEND")
    except snowflake.connector.errors.ProgrammingError:
        pass
    cur.close()
    conn.close()

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(P.md))
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
