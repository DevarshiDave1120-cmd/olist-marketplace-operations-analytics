"""Step 4 check: core star-schema row counts vs staging, fan-out check, and the
orders-without-items warning breakdown. Writes docs/core_counts.md.

Run from the repo root:  conda run -n olist python scripts/03_check_core.py
"""
from datetime import datetime
from pathlib import Path

import snowflake.connector

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "core_counts.md"

# core table -> (expected-count description, SQL on staging)
PAIRS = {
    "DIM_CUSTOMERS": ("distinct customer_unique_id in stg_customers",
                      "SELECT COUNT(DISTINCT customer_unique_id) FROM STAGING.STG_CUSTOMERS"),
    "DIM_SELLERS": ("rows in stg_sellers", "SELECT COUNT(*) FROM STAGING.STG_SELLERS"),
    "DIM_PRODUCTS": ("rows in stg_products", "SELECT COUNT(*) FROM STAGING.STG_PRODUCTS"),
    "DIM_DATE": ("days 2016-01-01..2020-12-31", "SELECT DATEDIFF(day, '2016-01-01', '2020-12-31') + 1"),
    "FCT_ORDERS": ("rows in stg_orders", "SELECT COUNT(*) FROM STAGING.STG_ORDERS"),
    "FCT_ORDER_ITEMS": ("rows in stg_order_items", "SELECT COUNT(*) FROM STAGING.STG_ORDER_ITEMS"),
}

# (label, SQL on core, SQL on staging) -- sums must be identical (no join fan-out)
SUMS = [
    ("sum of item price", "SELECT SUM(item_total) FROM CORE.FCT_ORDERS",
     "SELECT SUM(price) FROM STAGING.STG_ORDER_ITEMS"),
    ("sum of freight", "SELECT SUM(freight_total) FROM CORE.FCT_ORDERS",
     "SELECT SUM(freight_value) FROM STAGING.STG_ORDER_ITEMS"),
    ("sum of payments", "SELECT SUM(payment_total) FROM CORE.FCT_ORDERS",
     "SELECT SUM(payment_value) FROM STAGING.STG_ORDER_PAYMENTS"),
    ("orders with a review", "SELECT COUNT_IF(has_review) FROM CORE.FCT_ORDERS",
     "SELECT COUNT_IF(is_latest_review_for_order) FROM STAGING.STG_ORDER_REVIEWS"),
    ("sum of order_count in dim_customers", "SELECT SUM(order_count) FROM CORE.DIM_CUSTOMERS",
     "SELECT COUNT(*) FROM STAGING.STG_ORDERS"),
]


def main():
    conn = snowflake.connector.connect(connection_name="olist")
    cur = conn.cursor()
    cur.execute("USE WAREHOUSE OLIST_WH")
    cur.execute("USE DATABASE OLIST")
    one = lambda sql: cur.execute(sql).fetchone()[0]
    ok = True

    md = ["# Core star schema checks", "",
          f"Generated by `scripts/03_check_core.py` on {datetime.now():%Y-%m-%d %H:%M}.", "",
          "## Row counts vs staging", "",
          "| core table | expected from | expected | core rows | match |", "|---|---|---:|---:|---|"]
    for table, (desc, sql) in PAIRS.items():
        exp, got = one(sql), one(f"SELECT COUNT(*) FROM CORE.{table}")
        ok &= exp == got
        md.append(f"| {table.lower()} | {desc} | {exp:,} | {got:,} | {'OK' if exp == got else 'MISMATCH'} |")

    md += ["", "## No fan-out: totals in core equal staging", "",
           "| check | core | staging | match |", "|---|---:|---:|---|"]
    for label, core_sql, stg_sql in SUMS:
        c, s = one(core_sql), one(stg_sql)
        ok &= c == s
        md.append(f"| {label} | {c:,} | {s:,} | {'OK' if c == s else 'MISMATCH'} |")

    md += ["", "## Warning: orders without items (assert_every_order_has_item)", "",
           "| order_status | orders | with payments |", "|---|---:|---:|"]
    for status, n, paid in cur.execute(
            "SELECT order_status, COUNT(*), COUNT_IF(payment_total IS NOT NULL) "
            "FROM CORE.FCT_ORDERS WHERE item_count IS NULL GROUP BY 1 ORDER BY 2 DESC").fetchall():
        md.append(f"| {status} | {n:,} | {paid:,} |")

    try:
        cur.execute("ALTER WAREHOUSE OLIST_WH SUSPEND")
    except snowflake.connector.errors.ProgrammingError:
        pass
    conn.close()
    OUT.write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
